#ifndef EMG_TUNE_CFG_H
#define EMG_TUNE_CFG_H

/*
 * 这组宏是 EMG 算法的“正式默认参数”。
 *
 * 推荐使用流程：
 * 1. 先把 IMU_EMG_ONLY_TEST 置 1、emg_dbg 置 1，进入串口调参模式。
 * 2. 在上位机里观察 EMGDBG 曲线并调整参数。
 * 3. 调好后，把上位机导出的宏定义块回填到本文件。
 * 4. 再把 emg_do 置 1，让主业务中的 grip 走这套参数。
 *
 * 每个参数都尽量给出“物理意义 + 推荐范围 + 调大/调小的影响”，
 * 这样后续调参时不需要反复翻代码。
 */

/*
 * 包络上升系数：
 * - 物理意义：滤波后绝对值突然变大时，包络跟随得有多快。
 * - 推荐范围：0.10 ~ 0.60
 * - 调大：收缩时抬升更快，但也更容易跟着尖峰一起跳。
 * - 调小：更稳，但响应会变慢。
 */
#define EMG_TUNE_ENV_ATTACK_ALPHA        0.35f

/*
 * 包络释放系数：
 * - 物理意义：肌肉放松后，包络回落得有多快。
 * - 推荐范围：0.02 ~ 0.20
 * - 调大：放松后更快回零，但噪声环境下更容易抖。
 * - 调小：更平滑，但松手会显得拖尾更长。
 */
#define EMG_TUNE_ENV_RELEASE_ALPHA       0.08f

/*
 * 静息基线慢速上升系数：
 * - 物理意义：静息噪声长期慢慢抬高时，rest 基线跟上去的速度。
 * - 推荐范围：0.0005 ~ 0.01
 * - 调大：更能跟随长期噪声漂移，但也更容易把弱收缩误当成静息。
 * - 调小：更保守，更不容易被弱收缩带跑。
 */
#define EMG_TUNE_REST_RISE_ALPHA         0.002f

/*
 * 静息基线快速下降系数：
 * - 物理意义：噪声突然变小后，rest 基线往下回落的速度。
 * - 推荐范围：0.02 ~ 0.30
 * - 调大：回零更快。
 * - 调小：更稳，但恢复到低噪声基线的速度更慢。
 */
#define EMG_TUNE_REST_FALL_ALPHA         0.10f

/*
 * 峰值衰减系数：
 * - 物理意义：最近一次较大收缩结束后，peak 上界回落的速度。
 * - 推荐范围：0.001 ~ 0.02
 * - 调大：适应新幅值更快，但一次大收缩过后灵敏度会更快恢复。
 * - 调小：更稳，但 peak 会记住“很大的一次收缩”更久。
 */
#define EMG_TUNE_PEAK_DECAY_ALPHA        0.004f

/*
 * 最小动态跨度：
 * - 物理意义：即使 peak 和 rest 很接近，也至少保留这么大的可映射区间。
 * - 推荐范围：8 ~ 60
 * - 调大：静息更稳，不容易被小波动拉起，但需要更明显的收缩。
 * - 调小：更灵敏，但噪声更容易冒出来。
 */
#define EMG_TUNE_MIN_SPAN                18.0f

/*
 * 激活进入比例：
 * - 物理意义：包络超过 rest + span * on_ratio 时，才认为“可能开始抓握”。
 * - 推荐范围：0.10 ~ 0.45
 * - 调大：更不容易误触发。
 * - 调小：更容易进入抓握状态。
 */
#define EMG_TUNE_ON_RATIO                0.22f

/*
 * 激活退出比例：
 * - 物理意义：已经激活后，要低于 rest + span * off_ratio 才允许退出。
 * - 推荐范围：0.05 ~ 0.25
 * - 注意：必须小于 ON_RATIO，才能形成迟滞区。
 * - 调小：退出更慢、更稳。
 * - 调大：退出更快，但容易在阈值附近来回抖。
 */
#define EMG_TUNE_OFF_RATIO               0.12f

/*
 * 连续进入样本数：
 * - 物理意义：连续多少个采样点都超过进入门限，才真正进入激活态。
 * - 推荐范围：1 ~ 10
 * - 调大：更抗抖。
 * - 调小：进入更快。
 */
#define EMG_TUNE_ENTER_COUNT             3U

/*
 * 连续退出样本数：
 * - 物理意义：连续多少个采样点都低于退出门限，才真正退出激活态。
 * - 推荐范围：2 ~ 20
 * - 调大：放松后更稳，不容易误开合。
 * - 调小：松手更快。
 */
#define EMG_TUNE_EXIT_COUNT              8U

/*
 * 死区比例：
 * - 物理意义：把归一化输出最靠近静息的这一段直接压成 0。
 * - 推荐范围：0.05 ~ 0.25
 * - 调大：静息更容易稳在 0。
 * - 调小：很弱的收缩也能更早起量。
 */
#define EMG_TUNE_DEADZONE_RATIO          0.10f

/*
 * 非线性映射指数：
 * - 物理意义：决定 grip 从“刚起量”到“接近满量程”的手感曲线。
 * - 推荐范围：0.7 ~ 2.0
 * - 小于 1：前段更灵敏。
 * - 大于 1：前段更稳，后段更有力。
 */
#define EMG_TUNE_OUTPUT_GAMMA            1.20f

/*
 * 输出上升平滑系数：
 * - 物理意义：目标 grip 变大时，实际输出追上去的速度。
 * - 推荐范围：0.10 ~ 0.60
 * - 调大：闭合更快。
 * - 调小：闭合更平滑。
 */
#define EMG_TUNE_OUTPUT_ATTACK_ALPHA     0.30f

/*
 * 输出下降平滑系数：
 * - 物理意义：目标 grip 变小时，实际输出回落的速度。
 * - 推荐范围：0.05 ~ 0.40
 * - 调大：松手更快。
 * - 调小：松手更平滑。
 */
#define EMG_TUNE_OUTPUT_RELEASE_ALPHA    0.12f

#endif
